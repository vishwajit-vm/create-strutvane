/**
 * The generated app's environment variables. The skeleton's `.env.example` is the base: it lists
 * every key its config files read, production-safe (`APP_ENV=production`, `APP_DEBUG=false`) and
 * with every secret empty. One description here then renders both files from it (skeleton
 * INSTALLER.md §3): `.env` gets this machine's local values, `.env.example` keeps its safe values,
 * and keys the skeleton does not have yet (Docker mode, mail, the first admin, AI) are appended to
 * both under their own heading.
 *
 * Generated secrets are written **empty** here; the "secrets" setup step fills them into `.env`
 * only. A database password the user typed (their own server, no Docker) is the one value written
 * straight into `.env` — escaped, and never into `.env.example`.
 *
 * Two modes:
 * - **Docker** (everything in containers): the app reaches the database at `DB_HOST=db` and mail
 *   at `MAIL_HOST=mailpit` (service names); `FORWARD_*` ports are what the host sees (Sail names).
 * - **Without Docker:** SQLite (a file), or the user's own MySQL/PostgreSQL server.
 *
 * @module
 */
import { formatEnvValue, setEnvValue } from '../env-file.ts'
import { composeProjectName, postgresRoles, sqlIdentifier, testDatabaseName } from '../names.ts'
import { aiProviderInfo, DEFAULT_DATABASE_PORTS, type ProjectOptions } from '../options.ts'

/** One variable. */
export interface EnvVar {
  readonly key: string
  /** Local value written to `.env`. Empty for generated secrets (filled later). */
  readonly value: string
  /** Generated by the secrets step; always empty in `.env.example`. */
  readonly secret?: boolean
  /** Value for `.env.example` when it should differ from the local one. */
  readonly example?: string
  /**
   * Set in `.env` only; `.env.example` keeps the skeleton's production-safe value
   * (`APP_ENV=production`, `APP_DEBUG=false`, `LOG_LEVEL=info`).
   */
  readonly localOnly?: boolean
}

/** A titled block of variables. */
export interface EnvSection {
  readonly title: string
  /** The heading for keys the skeleton does not have, when it differs from {@link title}. */
  readonly appendTitle?: string
  readonly vars: readonly EnvVar[]
}

/** Values the user typed that belong in `.env` only. */
export interface TypedSecrets {
  /** The password of the user's own database server. */
  readonly dbPassword?: string
  /** A connection URL for the user's own server (it holds the password). */
  readonly dbUrl?: string
}

/**
 * The `DB_CONNECTION` value for a database: mysql, pgsql or sqlite (mariadb is written by setup
 * when the server says it is MariaDB; postgres is accepted as an alias of pgsql).
 *
 * @example
 * connectionName('postgres') // 'pgsql'
 */
export function connectionName(database: ProjectOptions['database']): 'mysql' | 'pgsql' | 'sqlite' {
  return database === 'postgres' ? 'pgsql' : database
}

/** Default host ports, before the ports step moves them away from busy ones. */
export const DEFAULT_PORTS: Readonly<{ app: 3000; mailpit: 8025; mysql: 3306; postgres: 5432 }> =
  Object.freeze({
    app: 3000,
    mailpit: 8025,
    ...DEFAULT_DATABASE_PORTS,
  } as const)

/**
 * Every key the secrets step must fill for these options.
 *
 * @example
 * secretKeys(options) // ['APP_KEY', 'DB_PASSWORD', 'DB_ROOT_PASSWORD']
 */
export function secretKeys(options: ProjectOptions): string[] {
  return buildEnvSections(options)
    .flatMap((section) => section.vars)
    .filter((variable) => variable.secret === true)
    .map((variable) => variable.key)
}

/**
 * The env sections for these options, in the order they appear in the files.
 *
 * @example
 * buildEnvSections(options).map((s) => s.title) // ['Application', 'Database', 'Logging', 'Cache, files and sessions', 'Mail', ...]
 */
export function buildEnvSections(options: ProjectOptions, typed: TypedSecrets = {}): EnvSection[] {
  const sections: (EnvSection | undefined)[] = [
    application(options),
    database(options, typed),
    logging(),
    storage(options),
    mail(options),
    docker(options),
    auth(options),
    ai(options),
  ]
  return sections.filter((section): section is EnvSection => section !== undefined)
}

function application(options: ProjectOptions): EnvSection {
  return {
    title: 'Application',
    vars: [
      { key: 'APP_NAME', value: options.name },
      { key: 'APP_ENV', value: 'local', localOnly: true },
      { key: 'APP_KEY', value: '', secret: true },
      { key: 'APP_DEBUG', value: 'true', localOnly: true },
      { key: 'APP_URL', value: `http://localhost:${DEFAULT_PORTS.app}` },
      { key: 'APP_PORT', value: String(DEFAULT_PORTS.app) },
    ],
  }
}

/**
 * Logging (ADR-0022): the channels come from the skeleton's `config/logging.ts` and its
 * `LOG_*` keys; only the local level differs (debug on this machine, info in the example).
 */
function logging(): EnvSection {
  return { title: 'Logging', vars: [{ key: 'LOG_LEVEL', value: 'debug', localOnly: true }] }
}

/**
 * The cache store for the cache/queue/sessions answer (INSTALLER.md §5, bug 7). The framework's
 * cache drivers are `file` and `memory`; there is no `database` store. The "no extra service"
 * answer is the `file` store, and Redis (`@strutvane/redis`, not released yet) switches
 * `CACHE_STORE` itself when `node strut install:redis` adds its store, so until then it is
 * `file` too: never a store the app cannot boot with.
 *
 * @example
 * cacheStore(options) // 'file'
 */
export function cacheStore(_options: ProjectOptions): 'file' {
  return 'file'
}

/**
 * Cache and file storage. `FILESYSTEM_DISK` stays `local` for the S3 answer as well:
 * `@strutvane/files` adds the s3 disk and switches it (`node strut install:files`).
 */
function storage(options: ProjectOptions): EnvSection {
  return {
    title: 'Cache, files and sessions',
    vars: [
      { key: 'CACHE_STORE', value: cacheStore(options) },
      { key: 'FILESYSTEM_DISK', value: 'local' },
    ],
  }
}

function database(options: ProjectOptions, typed: TypedSecrets): EnvSection {
  if (options.database === 'sqlite') {
    return {
      title: 'Database',
      vars: [
        { key: 'DB_CONNECTION', value: 'sqlite' },
        { key: 'DB_DATABASE', value: 'database/database.sqlite' },
        // Tests get their own database, so `npm test` never touches your local data.
        { key: 'DB_TEST_DATABASE', value: 'database/testing.sqlite' },
      ],
    }
  }
  if (options.connection !== undefined) {
    // The user's own server: their details, their password (typed, never generated).
    // Your own server (XAMPP, WAMP, MAMP, Laragon, Postgres.app, a local install, remote/cloud).
    const { host, port, database: name, username, socket, sslMode, sslCa } = options.connection
    const vars: EnvVar[] = [
      { key: 'DB_CONNECTION', value: connectionName(options.database) },
      { key: 'DB_HOST', value: host },
      { key: 'DB_PORT', value: String(port) },
      { key: 'DB_DATABASE', value: name },
      { key: 'DB_TEST_DATABASE', value: `${name.slice(0, 59)}_test` },
      { key: 'DB_USERNAME', value: username },
      { key: 'DB_PASSWORD', value: typed.dbPassword ?? '', example: '' },
      { key: 'DB_SSLMODE', value: sslMode },
    ]
    if (socket !== undefined) vars.push({ key: 'DB_SOCKET', value: socket })
    if (sslCa !== undefined) vars.push({ key: 'DB_SSL_CA', value: sslCa })
    // A URL wins over the separate keys; it holds the password, so the example stays empty.
    if (typed.dbUrl !== undefined) vars.push({ key: 'DB_URL', value: typed.dbUrl, example: '' })
    return { title: 'Database', vars }
  }
  return dockerDatabase(options)
}

/** Docker mode: the app talks to the `db` service on its container port; the host sees FORWARD_DB_PORT. */
function dockerDatabase(options: ProjectOptions): EnvSection {
  const server = options.database === 'postgres' ? 'postgres' : 'mysql'
  const port = String(DEFAULT_DATABASE_PORTS[server])
  const id = sqlIdentifier(options.name)
  const vars: EnvVar[] = [
    { key: 'DB_CONNECTION', value: connectionName(server) },
    { key: 'DB_HOST', value: 'db' },
    { key: 'DB_PORT', value: port },
    { key: 'FORWARD_DB_PORT', value: port },
    { key: 'DB_DATABASE', value: id },
    // Created next to the dev database on first start, so tests never touch local data.
    { key: 'DB_TEST_DATABASE', value: testDatabaseName(options.name) },
  ]
  if (server === 'postgres') {
    // Two roles (security review F-20): the app connects as a plain role (NOSUPERUSER,
    // NOBYPASSRLS, not the table owner), so row-level security really applies; migrations run as
    // the owner role.
    const roles = postgresRoles(options.name)
    vars.push(
      { key: 'DB_USERNAME', value: roles.app },
      { key: 'DB_PASSWORD', value: '', secret: true },
      { key: 'DB_MIGRATION_USERNAME', value: roles.owner },
      { key: 'DB_MIGRATION_PASSWORD', value: '', secret: true },
    )
  } else {
    vars.push({ key: 'DB_USERNAME', value: id }, { key: 'DB_PASSWORD', value: '', secret: true })
  }
  // The images need an administrator password; we generate one and the app never uses it.
  vars.push({ key: 'DB_ROOT_PASSWORD', value: '', secret: true })
  return { title: 'Database', appendTitle: 'Database (Docker mode)', vars }
}

function mail(options: ProjectOptions): EnvSection {
  if (!options.docker) {
    return { title: 'Mail', vars: [{ key: 'MAIL_MAILER', value: 'log' }] }
  }
  return {
    title: 'Mail',
    vars: [
      { key: 'MAIL_MAILER', value: 'smtp', example: 'log' },
      { key: 'MAIL_HOST', value: 'mailpit' },
      { key: 'MAIL_PORT', value: '1025' },
      // The Mailpit inbox on the host (it holds reset links: local only, never exposed).
      { key: 'FORWARD_MAILPIT_PORT', value: String(DEFAULT_PORTS.mailpit) },
    ],
  }
}

function docker(options: ProjectOptions): EnvSection | undefined {
  if (!options.docker) return undefined
  return {
    title: 'Docker (local only)',
    vars: [
      { key: 'COMPOSE_PROJECT_NAME', value: composeProjectName(options.name) },
      // The container runs as this user id on Linux, so files it writes are yours, not root's.
      // Docker Desktop (Windows, macOS) maps ownership itself; 1000 is the image's "node" user.
      { key: 'STRUT_UID', value: '1000' },
      { key: 'STRUT_GID', value: '1000' },
    ],
  }
}

/**
 * The first admin's address (sign-in only). Its password is never stored here (security review
 * F-18), and the sign-in features are not env keys: they live in config/auth.ts (decision #26).
 */
function auth(options: ProjectOptions): EnvSection | undefined {
  if (options.auth === 'none') return undefined
  return {
    title: 'First admin',
    vars: [{ key: 'SEED_ADMIN_EMAIL', value: options.adminEmail ?? `admin@${options.name}.test` }],
  }
}

/**
 * AI provider settings. The API key line is written EMPTY in both files and is not a generated
 * secret: the installer never asks for a key (it would land in shell history or CI logs); the
 * developer pastes it into `.env` later.
 */
function ai(options: ProjectOptions): EnvSection | undefined {
  if (options.aiProvider === undefined) return undefined
  const provider = aiProviderInfo(options.aiProvider)
  return {
    title: 'AI (paste your key here yourself; never commit it)',
    vars: [
      { key: 'AI_PROVIDER', value: provider.value },
      {
        key: provider.envKey,
        value: provider.envExample ?? '',
        example: provider.envExample ?? '',
      },
    ],
  }
}

/** The two env files of a new project. */
export interface EnvFiles {
  readonly env: string
  readonly example: string
}

/** Does the text have an active (not commented out) `KEY=` line? */
const hasKey = (text: string, key: string): boolean =>
  text.split('\n').some((line) => line.startsWith(`${key}=`))

/** The heading every `.env` starts with, instead of the example's "Copy to .env" header. */
const LOCAL_HEADER = '# Local settings for this machine. Never commit this file (it holds secrets).'

/**
 * Render `.env` and `.env.example` from the skeleton's rendered `.env.example`. Keys it has are
 * set in place (its comments and order stay); the others are appended under their section's
 * heading. `.env` gets local values (generated secrets still empty until the secrets step);
 * `.env.example` gets safe values only: every secret empty, `localOnly` keys left as the
 * skeleton wrote them. Every value goes through {@link setEnvValue} / {@link formatEnvValue}, so
 * nothing can inject a line.
 *
 * @example
 * renderEnvFiles(skeletonExample, buildEnvSections(options)).env
 */
export function renderEnvFiles(template: string, sections: readonly EnvSection[]): EnvFiles {
  const render = (example: boolean): string => {
    let text = template.endsWith('\n') ? template : `${template}\n`
    const appended: string[] = []
    for (const section of sections) {
      const lines: string[] = []
      for (const variable of section.vars) {
        const present = hasKey(text, variable.key)
        if (example && variable.localOnly === true && present) continue
        const value = !example
          ? variable.value
          : variable.secret === true
            ? ''
            : (variable.example ?? variable.value)
        if (present) text = setEnvValue(text, variable.key, value)
        else lines.push(`${variable.key}=${formatEnvValue(value)}`)
      }
      if (lines.length > 0)
        appended.push([`# ${section.appendTitle ?? section.title}`, ...lines].join('\n'))
    }
    const body = appended.length === 0 ? text : `${text}\n${appended.join('\n\n')}\n`
    if (example) return body
    // .env: the example's header ("Copy to .env ...") becomes the local file's warning.
    const blank = body.indexOf('\n\n')
    return `${LOCAL_HEADER}\n\n${blank === -1 ? body : body.slice(blank + 2)}`
  }
  return { env: render(false), example: render(true) }
}
